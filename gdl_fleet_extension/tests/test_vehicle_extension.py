"""Phase 2 - standard Vehicle extension."""

import frappe
from frappe.tests import IntegrationTestCase
from frappe.utils import nowdate

TEST_TYPE = "_Test GDL Pickup"


def get_test_company():
	company = frappe.db.get_value("Company", {}, "name")
	if not company:
		raise frappe.ValidationError("No Company on this site")
	return company


def make_vehicle_type():
	if not frappe.db.exists("Fleet Vehicle Type", TEST_TYPE):
		frappe.get_doc(
			{
				"doctype": "Fleet Vehicle Type",
				"vehicle_type_name": TEST_TYPE,
				"default_seating_capacity": 5,
				"default_fuel_type": "Diesel",
			}
		).insert()
	return TEST_TYPE


def new_vehicle(**kwargs):
	values = {
		"doctype": "Vehicle",
		"license_plate": frappe.generate_hash(length=8).upper(),
		"make": "Toyota",
		"model": "Hilux",
		"last_odometer": 1000,
		"fuel_type": "Diesel",
		"uom": "Litre",
		"company": get_test_company(),
		"vehicle_type": make_vehicle_type(),
		"ownership_type": "GDL Owned",
	}
	values.update(kwargs)
	return frappe.get_doc(values)


class TestVehicleExtension(IntegrationTestCase):
	@classmethod
	def setUpClass(cls):
		super().setUpClass()
		make_vehicle_type()

	# --- standard functionality must remain intact -------------------------
	def test_standard_vehicle_still_creatable(self):
		vehicle = new_vehicle()
		vehicle.insert()
		self.assertTrue(frappe.db.exists("Vehicle", vehicle.name))
		# document name is still the licence plate (standard naming untouched)
		self.assertEqual(vehicle.name, vehicle.license_plate)

	def test_standard_insurance_validation_still_fires(self):
		"""erpnext's own Vehicle.validate must still run under our doc_event."""
		vehicle = new_vehicle(start_date="2026-06-01", end_date="2026-01-01")
		self.assertRaises(frappe.ValidationError, vehicle.insert)

	def test_legacy_vehicle_without_id_still_saves(self):
		"""A Vehicle that predates this app must still be saveable (ID backfilled)."""
		vehicle = new_vehicle()
		vehicle.insert()
		# simulate a row created before gdl_vehicle_id existed
		frappe.db.set_value("Vehicle", vehicle.name, "gdl_vehicle_id", None, update_modified=False)

		doc = frappe.get_doc("Vehicle", vehicle.name)
		self.assertFalse(doc.gdl_vehicle_id)
		doc.model = "Hilux Revo"
		doc.save()
		self.assertTrue(doc.gdl_vehicle_id, "Vehicle ID was not backfilled on save")

	def test_backfill_gives_every_vehicle_an_id(self):
		from gdl_fleet_extension.setup.vehicle_fields import backfill_vehicle_ids

		vehicle = new_vehicle()
		vehicle.insert()
		frappe.db.set_value("Vehicle", vehicle.name, "gdl_vehicle_id", None, update_modified=False)

		backfill_vehicle_ids()
		self.assertTrue(frappe.db.get_value("Vehicle", vehicle.name, "gdl_vehicle_id"))
		self.assertFalse(
			frappe.get_all("Vehicle", filters=[["gdl_vehicle_id", "in", ["", None]]]),
			"some Vehicles still have no Vehicle ID after backfill",
		)

	# --- Vehicle ID ---------------------------------------------------------
	def test_vehicle_id_autogenerated(self):
		vehicle = new_vehicle()
		vehicle.insert()
		self.assertTrue(vehicle.gdl_vehicle_id)
		self.assertTrue(vehicle.gdl_vehicle_id.startswith("GDL-VEH-"))

	def test_vehicle_id_explicit_is_kept(self):
		vehicle = new_vehicle(gdl_vehicle_id="GDL-TEST-0001")
		vehicle.insert()
		self.assertEqual(vehicle.gdl_vehicle_id, "GDL-TEST-0001")

	def test_vehicle_id_must_be_unique(self):
		first = new_vehicle(gdl_vehicle_id="GDL-DUP-0001")
		first.insert()
		second = new_vehicle(gdl_vehicle_id="GDL-DUP-0001")
		self.assertRaises(frappe.ValidationError, second.insert)

	def test_vehicle_id_is_stable(self):
		"""set_only_once: the ID must not change after creation."""
		vehicle = new_vehicle()
		vehicle.insert()
		original = vehicle.gdl_vehicle_id
		vehicle.gdl_vehicle_id = "GDL-CHANGED-1"
		self.assertRaises(frappe.ValidationError, vehicle.save)
		vehicle.reload()
		self.assertEqual(vehicle.gdl_vehicle_id, original)

	# --- Site (standard Location) ------------------------------------------
	def test_leaf_site_accepted(self):
		vehicle = new_vehicle(site="Jamjee Farm")
		vehicle.insert()
		self.assertEqual(vehicle.site, "Jamjee Farm")

	def test_group_site_rejected(self):
		vehicle = new_vehicle(site="Farms")
		self.assertRaises(frappe.ValidationError, vehicle.insert)

	def test_site_tree_created(self):
		for site in (
			"GDL",
			"Head Office",
			"Farms",
			"Jamjee Farm",
			"Dochula Farm",
			"Dagapela Farm",
			"Gedu",
			"Samcholing",
			"Jigmeling",
		):
			self.assertTrue(frappe.db.exists("Location", site), f"missing Location {site}")

		self.assertEqual(frappe.db.get_value("Location", "Jamjee Farm", "parent_location"), "Farms")
		self.assertEqual(frappe.db.get_value("Location", "Farms", "parent_location"), "GDL")
		self.assertEqual(frappe.db.get_value("Location", "Head Office", "is_group"), 0)

	# --- other validations --------------------------------------------------
	def test_manufacturing_year_range(self):
		self.assertRaises(frappe.ValidationError, new_vehicle(manufacturing_year=1800).insert)
		self.assertRaises(frappe.ValidationError, new_vehicle(manufacturing_year=2999).insert)
		ok = new_vehicle(manufacturing_year=2020)
		ok.insert()
		self.assertEqual(ok.manufacturing_year, 2020)

	def test_opening_odometer_not_above_current(self):
		vehicle = new_vehicle(last_odometer=1000, opening_odometer=5000)
		self.assertRaises(frappe.ValidationError, vehicle.insert)

	def test_vehicle_type_is_mandatory(self):
		vehicle = new_vehicle()
		vehicle.vehicle_type = None
		self.assertRaises(frappe.exceptions.MandatoryError, vehicle.insert)

	def test_extended_fuel_type_options(self):
		"""Property Setter must have added the GDL fuel types."""
		vehicle = new_vehicle(fuel_type="Hybrid")
		vehicle.insert()
		self.assertEqual(vehicle.fuel_type, "Hybrid")

    # --- documents child table ---------------------------------------------
	def test_document_expiry_before_issue_rejected(self):
		vehicle = new_vehicle()
		vehicle.append(
			"documents",
			{
				"document_type": "Insurance",
				"issue_date": "2026-06-01",
				"expiry_date": "2026-01-01",
			},
		)
		self.assertRaises(frappe.ValidationError, vehicle.insert)

	def test_document_status_computed(self):
		vehicle = new_vehicle()
		vehicle.append(
			"documents",
			{"document_type": "Insurance", "issue_date": "2020-01-01", "expiry_date": "2020-06-01"},
		)
		vehicle.append(
			"documents",
			{"document_type": "Registration Certificate", "expiry_date": frappe.utils.add_days(nowdate(), 10)},
		)
		vehicle.append(
			"documents",
			{"document_type": "Fitness", "expiry_date": frappe.utils.add_years(nowdate(), 3)},
		)
		vehicle.append("documents", {"document_type": "Other"})
		vehicle.insert()

		self.assertEqual(vehicle.documents[0].status, "Expired")
		self.assertEqual(vehicle.documents[1].status, "Expiring Soon")
		self.assertEqual(vehicle.documents[2].status, "Valid")
		self.assertEqual(vehicle.documents[3].status, "Not Applicable")

	# --- no duplication of standard fields ---------------------------------
	def test_no_duplicate_fields_created(self):
		"""These GDL concepts must map onto STANDARD fields, not new ones."""
		meta = frappe.get_meta("Vehicle")
		custom_fieldnames = {df.fieldname for df in meta.fields if df.get("is_custom_field")}
		for standard_concept in (
			"registration_no",
			"current_odometer",
			"insurance_expiry",
			"insurance_start",
			"colour",
			"chassis_number",
			"policy_number",
		):
			self.assertNotIn(
				standard_concept,
				custom_fieldnames,
				f"{standard_concept} duplicates a standard Vehicle field",
			)

		for standard_field in (
			"license_plate",
			"chassis_no",
			"color",
			"insurance_company",
			"policy_no",
			"start_date",
			"end_date",
			"last_odometer",
		):
			self.assertTrue(meta.get_field(standard_field), f"standard field {standard_field} missing")
